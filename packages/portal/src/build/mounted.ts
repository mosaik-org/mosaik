import { existsSync } from "node:fs"
import { resolve } from "node:path"
import { WEB_BUNDLE_FILE } from "@mosaik/app-kit/bundle"
import { APP_STYLES_DIR } from "@mosaik/app-kit/panda"
import { appStyles } from "@mosaik/app-kit/vite"
import type { Plugin, PluginOption } from "vite"
import solid from "vite-plugin-solid"
import { SHARED_MODULES } from "./shared"

export interface MountedAppOptions {
  /** The module that default-exports `defineWebApp(...)`. Defaults to `web/index.tsx`. */
  readonly entry?: string
  /**
   * The module that default-exports `defineSearchProvider(...)` for the command palette.
   * Defaults to `web/search.ts` when that file exists.
   */
  readonly search?: string
  /** Defaults to `dist/web`; the backend serves it at `/apps/<id>/`. */
  readonly outDir?: string
}

const shared = new Set<string>(SHARED_MODULES)

/**
 * Builds an app's browser bundle for the shell: one ES module entry (content-hashed)
 * plus lazy chunks and CSS, with the shared modules left as bare imports for the
 * shell's import map. The search provider, if any, is a second entry: the palette loads
 * it without the app. Writes `mosaik-web.json` naming the entries and the entry's styles.
 */
export const mountedApp = (options: MountedAppOptions = {}): PluginOption[] => {
  const plugin: Plugin = {
    name: "mosaik:app",
    config: (config) => {
      const root = config.root ?? process.cwd()
      const search = resolve(root, options.search ?? "web/search.ts")
      if (options.search !== undefined && !existsSync(search)) throw new Error(`Search provider ${search} not found`)
      return {
        // Chunks are loaded relative to the entry's URL (`/apps/<id>/...`).
        base: "./",
        css: appStyles(root),
        resolve: {
          // `@mosaik/sdk/css` and its siblings: the app's own Panda runtime (prefixed classes), generated by `panda codegen`.
          alias: ["css", "jsx", "patterns", "tokens"].map((module) => ({
            find: `@mosaik/sdk/${module}`,
            replacement: resolve(root, APP_STYLES_DIR, module, "index.mjs"),
          })),
        },
        publicDir: false,
        build: {
          outDir: options.outDir ?? "dist/web",
          emptyOutDir: true,
          target: "es2023",
          sourcemap: true,
          rolldownOptions: {
            input: {
              entry: resolve(root, options.entry ?? "web/index.tsx"),
              ...(existsSync(search) ? { search } : {}),
            },
            preserveEntrySignatures: "strict",
            external: (id: string) => shared.has(id),
            output: {
              entryFileNames: "[name]-[hash].js",
              chunkFileNames: "chunks/[name]-[hash].js",
              assetFileNames: "assets/[name]-[hash][extname]",
            },
          },
        },
      }
    },
    generateBundle(_, bundle) {
      const entryChunk = (name: string) =>
        Object.values(bundle).find((output) => output.type === "chunk" && output.isEntry && output.name === name)
      const chunk = entryChunk("entry")
      if (chunk === undefined || chunk.type !== "chunk") return this.error("No entry chunk was built")
      const styles = [...(chunk.viteMetadata?.importedCss ?? [])]
      const search = entryChunk("search")?.fileName ?? null
      this.emitFile({
        type: "asset",
        fileName: WEB_BUNDLE_FILE,
        source: `${JSON.stringify({ entry: chunk.fileName, styles, search }, null, 2)}\n`,
      })
    },
  }
  return [solid(), plugin]
}
